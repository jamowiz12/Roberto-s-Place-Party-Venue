create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  role text not null default 'customer',
  created_at timestamptz not null default now()
);

create table if not exists public.packages (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  price_per_person numeric(10,2),
  inclusions jsonb not null default '[]',
  active boolean not null default true
);

create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id),
  package_id bigint references public.packages(id),
  event_type text,
  event_date date,
  event_time text,
  guest_count integer not null,
  selected_items jsonb not null default '[]',
  equipment jsonb not null default '[]',
  total numeric(10,2) not null default 0,
  status text not null default 'pending',
  payment_status text not null default 'unpaid',
  receipt_url text,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.packages enable row level security;
alter table public.reservations enable row level security;

-- Revoke all existing privileges, including old column grants, before applying minimum grants.
revoke all privileges on table public.profiles from anon, authenticated;
revoke all privileges (id, full_name, phone, role, created_at)
  on table public.profiles from anon, authenticated;

revoke all privileges on table public.packages from anon, authenticated;
revoke all privileges (id, name, description, price_per_person, inclusions, active)
  on table public.packages from anon, authenticated;

revoke all privileges on table public.reservations from anon, authenticated;
revoke all privileges (id, user_id, package_id, event_type, event_date, event_time,
  guest_count, selected_items, equipment, total, status, payment_status, receipt_url,
  created_at)
  on table public.reservations from anon, authenticated;

-- Minimum table and column privileges.
grant select on table public.profiles to authenticated;
grant update (full_name, phone) on table public.profiles to authenticated;

grant select on table public.packages to anon, authenticated;

grant select on table public.reservations to authenticated;
grant update (status, payment_status) on table public.reservations to authenticated;

-- SECURITY DEFINER role check. Empty search_path and fully qualified references prevent search-path abuse.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public, anon;
revoke all on function public.is_admin() from authenticated;
grant execute on function public.is_admin() to authenticated;

-- Idempotent policies.
DROP POLICY IF EXISTS "profiles readable by owner" ON public.profiles;
DROP POLICY IF EXISTS "profiles readable by owner or admin" ON public.profiles;
CREATE POLICY "profiles readable by owner or admin" ON public.profiles
FOR SELECT TO authenticated
USING (auth.uid() = id OR public.is_admin());

DROP POLICY IF EXISTS "profiles editable by owner" ON public.profiles;
CREATE POLICY "profiles editable by owner" ON public.profiles
FOR UPDATE TO authenticated
USING (auth.uid() = id)
WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "active packages publicly readable" ON public.packages;
CREATE POLICY "active packages publicly readable" ON public.packages
FOR SELECT TO anon, authenticated
USING (active = true);

DROP POLICY IF EXISTS "administrators read all packages" ON public.packages;
CREATE POLICY "administrators read all packages" ON public.packages
FOR SELECT TO authenticated
USING (public.is_admin());

DROP POLICY IF EXISTS "reservations readable by owner or admin" ON public.reservations;
CREATE POLICY "reservations readable by owner or admin" ON public.reservations
FOR SELECT TO authenticated
USING (auth.uid() = user_id OR public.is_admin());

DROP POLICY IF EXISTS "customers create reservations" ON public.reservations;
DROP POLICY IF EXISTS "reservation direct insert denied" ON public.reservations;

DROP POLICY IF EXISTS "admins update reservations" ON public.reservations;
CREATE POLICY "admins update reservations" ON public.reservations
FOR UPDATE TO authenticated
USING (public.is_admin())
WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS "receipt uploads by owner" ON storage.objects;
CREATE POLICY "receipt uploads by owner" ON storage.objects
FOR INSERT TO authenticated
WITH CHECK (
  bucket_id = 'payment-receipts'
  AND (storage.foldername(name))[1] = auth.uid()::text
);

DROP POLICY IF EXISTS "receipt read by owner or admin" ON storage.objects;
CREATE POLICY "receipt read by owner or admin" ON storage.objects
FOR SELECT TO authenticated
USING (
  bucket_id = 'payment-receipts'
  AND (
    (storage.foldername(name))[1] = auth.uid()::text
    OR public.is_admin()
  )
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, role)
    values (
      new.id,
      coalesce(new.raw_user_meta_data->>'full_name', ''),
      'customer'
    )
  on conflict (id) do update set
    full_name = coalesce(excluded.full_name, public.profiles.full_name);
  return new;
end;
$$;

revoke all on function public.handle_new_user() from public, anon;
revoke all on function public.handle_new_user() from authenticated;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

insert into storage.buckets (id, name, public)
values ('payment-receipts', 'payment-receipts', false)
on conflict (id) do update set
  public = false,
  file_size_limit = 5242880,
  allowed_mime_types = array['image/jpeg','image/png','image/webp','application/pdf']::text[];

update storage.buckets
set
  public = false,
  file_size_limit = 5242880,
  allowed_mime_types = array['image/jpeg','image/png','image/webp','application/pdf']::text[]
where id = 'payment-receipts';

create or replace function public.create_reservation(
  p_package_id bigint,
  p_event_type text,
  p_event_date date,
  p_event_time text,
  p_guest_count integer,
  p_selected_items jsonb,
  p_equipment jsonb
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_price numeric(10,2);
  v_total numeric(10,2);
  v_reservation_id bigint;
begin
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  IF p_guest_count IS NULL OR p_guest_count < 1 OR p_guest_count > 5000 THEN
    RAISE EXCEPTION 'Invalid guest count';
  END IF;

  IF p_event_date IS NULL OR p_event_date < CURRENT_DATE THEN
    RAISE EXCEPTION 'Invalid event date';
  END IF;

  IF p_event_type IS NULL OR btrim(p_event_type) = '' THEN
    RAISE EXCEPTION 'Event type is required';
  END IF;

  IF p_event_time IS NULL OR p_event_time !~ '^([01][0-9]|2[0-3]):[0-5][0-9]$' THEN
    RAISE EXCEPTION 'Invalid event time';
  END IF;

  IF p_package_id IS NULL THEN
    RAISE EXCEPTION 'A valid active package is required';
  END IF;

  SELECT price_per_person
    INTO v_price
    FROM public.packages
    WHERE id = p_package_id
      AND active = true;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Invalid or inactive package';
  END IF;

  IF v_price IS NULL OR v_price <= 0 THEN
    RAISE EXCEPTION 'Package price must be valid and greater than zero';
  END IF;

  v_total := v_price * p_guest_count;

  INSERT INTO public.reservations (
    user_id, package_id, event_type, event_date, event_time,
    guest_count, selected_items, equipment, total,
    status, payment_status
  ) VALUES (
    v_user_id, p_package_id, btrim(p_event_type), p_event_date, p_event_time,
    p_guest_count, COALESCE(p_selected_items, '[]'::jsonb),
    COALESCE(p_equipment, '[]'::jsonb), v_total,
    'pending', 'unpaid'
  )
  RETURNING id INTO v_reservation_id;

  RETURN v_reservation_id;
END;
$$;

revoke all on function public.create_reservation(bigint, text, date, text, integer, jsonb, jsonb) from public, anon;
grant execute on function public.create_reservation(bigint, text, date, text, integer, jsonb, jsonb) to authenticated;

create or replace function public.set_reservation_receipt(
  p_reservation_id bigint,
  p_receipt_path text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
begin
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  IF p_receipt_path IS NULL
     OR p_receipt_path NOT LIKE v_user_id::text || '/%'
     OR p_receipt_path !~* '\.(jpe?g|png|webp|pdf)$' THEN
    RAISE EXCEPTION 'Invalid receipt path';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM storage.objects
    WHERE bucket_id = 'payment-receipts'
      AND name = p_receipt_path
  ) THEN
    RAISE EXCEPTION 'Receipt object not found in private storage';
  END IF;

  UPDATE public.reservations
  SET receipt_url = p_receipt_path,
      payment_status = 'pending_verification'
  WHERE id = p_reservation_id
    AND user_id = v_user_id
    AND payment_status IS DISTINCT FROM 'paid';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Reservation cannot accept a receipt';
  END IF;
end;
$$;

revoke all on function public.set_reservation_receipt(bigint, text) from public, anon;
grant execute on function public.set_reservation_receipt(bigint, text) to authenticated;

alter table public.reservations enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'reservations_status_check'
      and conrelid = 'public.reservations'::regclass
  ) then
    alter table public.reservations
      add constraint reservations_status_check
      check (status in ('pending', 'approved', 'rejected'));
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'reservations_payment_status_check'
      and conrelid = 'public.reservations'::regclass
  ) then
    alter table public.reservations
      add constraint reservations_payment_status_check
      check (payment_status in ('unpaid', 'pending_verification', 'paid', 'rejected'));
  end if;
end;
$$;
