create or replace function public.refresh_reservation_ledger_payment_status(
  p_reservation_id bigint
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_reservation_total numeric(10, 2);
  v_current_status text;
  v_verified_total numeric(10, 2);
  v_has_pending boolean;
  v_has_ledger_rows boolean;
  v_next_status text;
begin
  select total, payment_status
  into v_reservation_total, v_current_status
  from public.reservations
  where id = p_reservation_id;

  if not found then
    return;
  end if;

  select
    coalesce(sum(amount) filter (where status = 'verified'), 0)::numeric(10, 2),
    coalesce(bool_or(status = 'pending_verification'), false),
    count(*) > 0
  into v_verified_total, v_has_pending, v_has_ledger_rows
  from public.reservation_payments
  where reservation_id = p_reservation_id;

  if v_verified_total >= v_reservation_total then
    v_next_status := 'paid';
  elsif v_has_pending then
    v_next_status := 'pending_verification';
  elsif v_current_status = 'paid' and not v_has_ledger_rows then
    return;
  else
    v_next_status := 'unpaid';
  end if;

  update public.reservations
  set payment_status = v_next_status
  where id = p_reservation_id
    and payment_status is distinct from v_next_status;
end;
$$;

