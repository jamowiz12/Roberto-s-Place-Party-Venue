-- Keep the existing private bucket and its current accepted MIME types, adding
-- text/plain for downloadable acknowledgments. No public receipt URL is created.
update storage.buckets
set public = false,
    allowed_mime_types = (
      select array_agg(distinct accepted.mime order by accepted.mime)
      from unnest(
        coalesce(
          allowed_mime_types,
          array['image/jpeg', 'image/png', 'image/webp', 'application/pdf']::text[]
        ) || array['text/plain']::text[]
      ) as accepted(mime)
    )
where id = 'payment-receipts';

