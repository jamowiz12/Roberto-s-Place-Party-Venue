  v_customer_id uuid := auth.uid();
  v_role text;
  v_reservation public.reservations%rowtype;
  v_amount numeric(10, 2);
  v_verified_total numeric(10, 2);
  v_pending_total numeric(10, 2);
  v_remaining numeric(10, 2);
  v_payment_id bigint;
begin
  if v_customer_id is null then
    raise exception 'Authentication required';
  end if;

  select role into v_role
  from public.profiles
  where id = v_customer_id;
  if v_role is distinct from 'customer' then
    raise exception 'Customer authorization required';
  end if;

  if p_payment_type is null
     or p_payment_type not in ('down_payment', 'full_payment', 'balance_payment') then
    raise exception 'Invalid payment type';
  end if;
  if p_payment_method is null
     or p_payment_method not in ('cash', 'gcash_in_person', 'maya_in_person') then
    raise exception 'Invalid payment method';
  end if;
  if p_request_key is null then
    raise exception 'Payment request key is required';
  end if;
  if length(coalesce(p_reference_number, '')) > 100 then
    raise exception 'Payment reference numbers must be 100 characters or fewer';
  end if;

  select * into v_reservation
  from public.reservations
  where id = p_reservation_id
    and user_id = v_customer_id
  for update;
  if not found then
    raise exception 'Reservation not found';
  end if;
    if v_reservation.status = 'rejected' then
    raise exception 'Payment is not available for a rejected reservation';
  end if;

    -- Do not mix an unresolved legacy receipt with the new payment ledger.
  if v_reservation.receipt_url is not null
     and v_reservation.payment_status = 'pending_verification'
     and not exists (
       select 1
       from public.reservation_payments
       where reservation_id = p_reservation_id
     ) then
    raise exception 'A legacy receipt is awaiting review';
  end if;

  if v_reservation.payment_status = 'paid'
     and not exists (
       select 1
       from public.reservation_payments
       where reservation_id = p_reservation_id
     ) then
    raise exception 'This reservation is already marked paid in legacy records';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(p_request_key::text, 0));
  select id into v_payment_id
  from public.reservation_payments
  where request_key = p_request_key;
  if found then
    if not exists (
      select 1 from public.reservation_payments
      where id = v_payment_id
        and customer_id = v_customer_id
        and reservation_id = p_reservation_id
    ) then
      raise exception 'Payment request key has already been used';
    end if;
    return v_payment_id;
  end if;

  if p_payment_type = 'down_payment' and exists (
    select 1 from public.reservation_payments
    where reservation_id = p_reservation_id
      and status in ('verified', 'pending_verification')
  ) then
    raise exception 'A down payment has already been submitted or recorded';
  end if;

  select coalesce(sum(amount), 0)::numeric(10, 2)
  into v_verified_total
  from public.reservation_payments
  where reservation_id = p_reservation_id
    and status = 'verified';
  select coalesce(sum(amount), 0)::numeric(10, 2)
  into v_pending_total
  from public.reservation_payments
  where reservation_id = p_reservation_id
    and status = 'pending_verification';

  v_remaining := v_reservation.total - v_verified_total - v_pending_total;
  if v_remaining <= 0 then
    raise exception 'Reservation has no remaining balance';
  end if;

  if p_payment_type = 'down_payment' then
    v_amount := round(v_reservation.total * 0.50, 2);
  elsif p_payment_type = 'full_payment' then
    v_amount := v_remaining;
  else
    if p_requested_amount is null or p_requested_amount <= 0 then
      raise exception 'Enter a valid balance payment amount';
    end if;
    v_amount := round(p_requested_amount, 2);
  end if;

  if v_amount <= 0 or v_amount > v_remaining then
    raise exception 'Payment amount exceeds the remaining balance';
  end if;

  if p_receipt_path is not null then
    if p_receipt_path not like v_customer_id::text || '/payments/%' then
      raise exception 'Invalid payment proof location';
    end if;
    if not exists (
      select 1 from storage.objects
      where bucket_id = 'payment-receipts'
        and name = p_receipt_path
    ) then
      raise exception 'Payment proof was not found in private storage';
    end if;
  end if;
  if p_payment_method in ('gcash_in_person', 'maya_in_person')
     and p_receipt_path is null then
    raise exception 'Payment proof is required for in-person wallet payments';
  end if;

  insert into public.reservation_payments (
    reservation_id, customer_id, amount, payment_method, payment_type, status,
    receipt_path, reference_number, request_key
  ) values (
    p_reservation_id, v_customer_id, v_amount, p_payment_method, p_payment_type,
    'pending_verification', p_receipt_path,
    nullif(btrim(p_reference_number), ''), p_request_key
  ) returning id into v_payment_id;

  insert into public.reservation_payment_audit (
    payment_id, reservation_id, actor_id, action, previous_value, new_value, reason
  ) values (
    v_payment_id, p_reservation_id, v_customer_id, 'submitted', null,
    jsonb_build_object(
      'amount', v_amount,
      'payment_method', p_payment_method,
      'payment_type', p_payment_type,
      'status', 'pending_verification',
      'receipt_path', p_receipt_path,
      'reference_number', nullif(btrim(p_reference_number), '')
    ),
    'Customer submitted a payment for review.'
  );

  perform public.refresh_reservation_ledger_payment_status(p_reservation_id);
  return v_payment_id;
end;
$$;

