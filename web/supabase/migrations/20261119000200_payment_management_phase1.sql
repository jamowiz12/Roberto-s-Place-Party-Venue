create or replace function public.set_reservation_receipt(
  p_reservation_id bigint,
  p_receipt_path text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_reservation public.reservations%rowtype;
  v_role text;
begin
  if v_user_id is null then
    raise exception 'Authentication required';
  end if;

  select *
  into v_reservation
  from public.reservations
  where id = p_reservation_id and user_id = v_user_id
  for update;

  if not found then
    raise exception 'Reservation not found';
  end if;

  select role into v_role
  from public.profiles
  where id = v_user_id;
  if v_role is distinct from 'customer' then
    raise exception 'Customer authorization required';
  end if;

  if exists (
    select 1 from public.reservation_payments
    where reservation_id = p_reservation_id
  ) then
    raise exception 'Use the payment ledger for this reservation';
  end if;
  if v_reservation.payment_status = 'paid' then
    raise exception 'Reservation is already marked paid';
  end if;

  if p_receipt_path is null
     or p_receipt_path not like v_user_id::text || '/%'
     or p_receipt_path !~* '\.(jpe?g|png|webp|pdf)$' then
    raise exception 'Invalid receipt path';
  end if;
  if not exists (
    select 1 from storage.objects
    where bucket_id = 'payment-receipts'
      and name = p_receipt_path
  ) then
    raise exception 'Receipt object not found in private storage';
  end if;

  update public.reservations
  set receipt_url = p_receipt_path,
      payment_status = 'pending_verification'
  where id = p_reservation_id
    and user_id = v_user_id;
end;
$$;

