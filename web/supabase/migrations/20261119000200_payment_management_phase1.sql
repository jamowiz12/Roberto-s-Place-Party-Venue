create or replace function public.submit_reservation_payment(
  p_reservation_id bigint,
  p_payment_type text,
  p_payment_method text,
  p_requested_amount numeric,
  p_receipt_path text,
  p_reference_number text,
  p_request_key uuid
)
returns bigint
