  ) values (
    v_payment_id, p_reservation_id, v_admin_id, 'admin_recorded', null,
    jsonb_build_object(
      'amount', v_amount,
      'payment_method', p_payment_method,
      'payment_type', p_payment_type,
      'status', 'verified',
      'acknowledgment_reference', v_reference
    ),
    btrim(p_reason)
  );

  perform public.refresh_reservation_ledger_payment_status(p_reservation_id);
  return v_payment_id;
end;
$$;

create or replace function public.set_payment_acknowledgment_path(
  p_payment_id bigint,
  p_acknowledgment_path text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_admin_id uuid := auth.uid();
  v_payment public.reservation_payments%rowtype;
begin
  if v_admin_id is null or not public.is_admin() then
    raise exception 'Administrator authorization required';
  end if;

  select * into v_payment
  from public.reservation_payments
  where id = p_payment_id
  for update;
  if not found or v_payment.status <> 'verified'
     or v_payment.acknowledgment_reference is null then
    raise exception 'Verified payment not found';
  end if;

  if p_acknowledgment_path is distinct from (
    v_payment.customer_id::text || '/acknowledgments/payment-' ||
    v_payment.id::text || '-' || v_payment.acknowledgment_reference || '.txt'
  ) then
    raise exception 'Invalid acknowledgment location';
  end if;
  if not exists (
    select 1 from storage.objects
    where bucket_id = 'payment-receipts'
      and name = p_acknowledgment_path
  ) then
    raise exception 'Acknowledgment file was not found in private storage';
  end if;

  update public.reservation_payments
  set acknowledgment_path = p_acknowledgment_path
  where id = p_payment_id;

  insert into public.reservation_payment_audit (
    payment_id, reservation_id, actor_id, action, previous_value, new_value, reason
  ) values (
    p_payment_id, v_payment.reservation_id, v_admin_id, 'acknowledgment_stored',
    jsonb_build_object('acknowledgment_path', v_payment.acknowledgment_path),
    jsonb_build_object('acknowledgment_path', p_acknowledgment_path),
    'Generated verified payment acknowledgment.'
  );
end;
$$;

