create or replace function public.verify_reservation_payment(
  p_payment_id bigint,
  p_decision text,
  p_reason text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_admin_id uuid := auth.uid();
  v_payment public.reservation_payments%rowtype;
  v_reservation public.reservations%rowtype;
  v_reservation_id bigint;
  v_verified_total numeric(10, 2);
  v_remaining numeric(10, 2);
  v_reference text;
begin
  if v_admin_id is null or not public.is_admin() then
    raise exception 'Administrator authorization required';
  end if;

  if p_decision is null or p_decision not in ('verified', 'rejected') then
    raise exception 'Invalid payment decision';
  end if;
  if length(btrim(coalesce(p_reason, ''))) < 3 then
    raise exception 'A reason of at least 3 characters is required';
  end if;
  if length(btrim(p_reason)) > 500 then
    raise exception 'The audit reason is too long';
  end if;

  select reservation_id into v_reservation_id
  from public.reservation_payments
  where id = p_payment_id;
  if not found then
    raise exception 'Payment not found';
  end if;

  -- Lock reservation first to serialize all payment operations.
  select * into v_reservation
  from public.reservations
  where id = v_reservation_id
  for update;
  if not found then
    raise exception 'Reservation not found';
  end if;
  if v_reservation.status = 'rejected' then
    raise exception 'Cannot review payment for a rejected reservation';
  end if;

  select * into v_payment
  from public.reservation_payments
  where id = p_payment_id
  for update;
  if not found or v_payment.status <> 'pending_verification' then
    raise exception 'Payment is no longer awaiting verification';
  end if;

  if p_decision = 'verified' then
    select coalesce(sum(amount), 0)::numeric(10, 2)
    into v_verified_total
    from public.reservation_payments
    where reservation_id = v_payment.reservation_id
      and status = 'verified';

    v_remaining := v_reservation.total - v_verified_total;
    if v_remaining < v_payment.amount then
      raise exception 'Verifying this payment would exceed the reservation total';
    end if;

    v_reference := 'RP-' ||
      to_char(clock_timestamp() at time zone 'UTC', 'YYYYMMDD') ||
      '-' || lpad(v_payment.id::text, 8, '0');

    update public.reservation_payments
    set status = 'verified',
        verified_by = v_admin_id,
        verified_at = now(),
        acknowledgment_reference = v_reference
    where id = p_payment_id;
  else
    update public.reservation_payments
    set status = 'rejected'
    where id = p_payment_id;
  end if;

  insert into public.reservation_payment_audit (
    payment_id, reservation_id, actor_id, action, previous_value, new_value, reason
  ) values (
    p_payment_id,
    v_payment.reservation_id,
    v_admin_id,
    p_decision,
    jsonb_build_object(
      'status', v_payment.status,
      'verified_by', v_payment.verified_by,
      'verified_at', v_payment.verified_at
    ),
    jsonb_build_object(
      'status', p_decision,
      'verified_by', case when p_decision = 'verified' then v_admin_id else null end,
      'verified_at', case when p_decision = 'verified' then now() else null end,
      'acknowledgment_reference', v_reference
    ),
    btrim(p_reason)
  );

  perform public.refresh_reservation_ledger_payment_status(v_payment.reservation_id);
  return p_payment_id;
end;
$$;

