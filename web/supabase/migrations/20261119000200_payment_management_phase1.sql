-- Preserve root-level legacy receipt upload paths while putting new proof uploads
-- in the owner's /payments/ folder. Customers cannot upload acknowledgment files.
drop policy if exists "receipt uploads by owner" on storage.objects;
create policy "receipt uploads by owner" on storage.objects
for insert to authenticated
with check (
  bucket_id = 'payment-receipts'
  and (storage.foldername(name))[1] = auth.uid()::text
  and (
    coalesce(array_length(storage.foldername(name), 1), 0) = 1
    or (storage.foldername(name))[2] = 'payments'
  )
);

